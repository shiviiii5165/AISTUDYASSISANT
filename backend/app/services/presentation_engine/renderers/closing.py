"""Closing renderer — Branded closing slide with Q&A."""
from pptx.slide import Slide
from pptx.util import Inches
from pptx.enum.text import PP_ALIGN, MSO_ANCHOR
from .. import SlideContent, ThemeColors
from ..tokens import (
    SLIDE_WIDTH, SLIDE_HEIGHT, MARGIN_LEFT, CONTENT_WIDTH,
    Typography,
)
from .base import add_filled_rect, add_text_box


def render_closing(slide: Slide, content: SlideContent, theme: ThemeColors, **kw) -> None:
    """Render a branded closing slide."""
    # Dark background matching cover
    add_filled_rect(slide, 0, 0, SLIDE_WIDTH, SLIDE_HEIGHT, theme.dark_bg)

    # Top accent bar
    add_filled_rect(slide, 0, 0, SLIDE_WIDTH, Inches(0.12), theme.primary)

    # Thank You text
    add_text_box(
        slide, "Thank You",
        MARGIN_LEFT, Inches(2.0), CONTENT_WIDTH, Inches(1.2),
        token=Typography.HERO_TITLE, color=theme.text_on_dark,
        alignment=PP_ALIGN.CENTER, anchor=MSO_ANCHOR.MIDDLE,
    )

    # Subtitle
    subtitle = content.subtitle or "Questions & Discussion"
    add_text_box(
        slide, subtitle,
        MARGIN_LEFT, Inches(3.2), CONTENT_WIDTH, Inches(0.5),
        token=Typography.HERO_SUBTITLE, color=theme.text_muted,
        alignment=PP_ALIGN.CENTER,
    )

    # Bottom accent line
    add_filled_rect(
        slide, Inches(5.5), Inches(4.2), Inches(2.3), Inches(0.04), theme.primary
    )

    # Key takeaways as compact list
    takeaways = kw.get("key_takeaways", [])
    if takeaways:
        items_text = "  ".join([f"- {t}" for t in takeaways[:5]])
        add_text_box(
            slide, items_text,
            Inches(1.5), Inches(4.8), Inches(10.3), Inches(1.0),
            token=Typography.CAPTION, color=theme.text_on_dark,
            alignment=PP_ALIGN.CENTER,
        )

    # Bottom branding
    add_filled_rect(
        slide, 0, SLIDE_HEIGHT - Inches(0.7),
        SLIDE_WIDTH, Inches(0.7), theme.dark_surface,
    )
    add_text_box(
        slide, "Generated by LearnByGenie AI",
        MARGIN_LEFT, SLIDE_HEIGHT - Inches(0.55),
        CONTENT_WIDTH, Inches(0.35),
        token=Typography.FOOTNOTE, color=theme.border,
        alignment=PP_ALIGN.CENTER,
    )
