"""
Presentation Engine — Semantic & Deterministic Cache
=====================================================
Calculates normalized request hashes to return cached presentations instantly
without wasting model tokens or re-rendering identical decks.

vNEXT: PLANNER_VERSION is included in the hash to prevent cache poisoning
between legacy-planner and blueprint-planner output (spec §12).
"""
from app.core.logging import logger
import hashlib
import json
from typing import Optional, Dict, Any
from app.db.supabase_client import supabase
from .schemas import PresentationConfig, PresentationSpec

# Bump this when the planner output schema changes significantly.
# Prevents a pre-vNext fixed-story cached PresentationSpec from being
# returned as if generated by the new blueprint planner.
PLANNER_VERSION = "vnext_phase1"
STORY_GRAMMAR_VERSION = "1.0"
BLUEPRINT_SCHEMA_VERSION = "1.0"
TOPIC_INTELLIGENCE_VERSION = "1.0"
CONTENT_ENGINE_VERSION = "3.3"

# Phase 3.1 — Visual Planning version tokens
VISUAL_ENGINE_VERSION = "3.0"
DESIGN_DNA_VERSION = "3.0"
VISUAL_RHYTHM_VERSION = "3.0"


def compute_presentation_hash(config: PresentationConfig) -> str:
    """Compute a deterministic hash for a given presentation configuration.
    
    Includes all semantic version fences and input dimensions to prevent
    stale cache poisoning between planner versions (spec §12).
    """
    # Compute custom_context hash if present
    custom_context_hash = ""
    if hasattr(config, "custom_context") and config.custom_context:
        custom_context_hash = hashlib.sha256(
            config.custom_context.encode("utf-8")
        ).hexdigest()[:16]

    normalized_dict = {
        # ─── Input Identity ────────────────────────────────────
        "topic": config.topic.strip().lower(),
        "slide_count": config.slide_count,
        "audience": config.audience.strip().lower(),
        "language": config.language.strip().lower(),
        "depth": config.depth.strip().lower(),
        "design": config.design.value if hasattr(config.design, 'value') else str(config.design),
        "theme": config.theme.strip().lower(),
        "source_type": config.source_type,
        "source_id": config.source_id or "",
        "custom_context_hash": custom_context_hash,
        # ─── Feature Toggles ──────────────────────────────────
        "options": {
            "diagrams": config.enable_diagrams,
            "images": config.enable_images,
            "speaker_notes": config.enable_speaker_notes,
            "sources": config.enable_sources,
            "examples": config.enable_examples,
            "quiz": config.enable_quiz,
        },
        # ─── Semantic Version Fences ──────────────────────────
        # Cache keys from different versions never collide,
        # preventing stale cache poisoning.
        "planner_version": PLANNER_VERSION,
        "story_grammar_version": STORY_GRAMMAR_VERSION,
        "blueprint_schema_version": BLUEPRINT_SCHEMA_VERSION,
        "topic_intelligence_version": TOPIC_INTELLIGENCE_VERSION,
        "content_engine_version": CONTENT_ENGINE_VERSION,
    }
    raw_str = json.dumps(normalized_dict, sort_keys=True)
    return hashlib.sha256(raw_str.encode("utf-8")).hexdigest()



async def get_cached_presentation(config: PresentationConfig) -> Optional[Dict[str, Any]]:
    """Retrieve cached presentation spec from Supabase deck_cache if present."""
    if not supabase:
        return None
    cache_key = compute_presentation_hash(config)
    try:
        res = supabase.table("deck_cache")\
            .select("deck_json")\
            .eq("topic", f"v2_{cache_key}")\
            .execute()
        if res.data and len(res.data) > 0:
            return res.data[0].get("deck_json")
    except Exception as e:
        logger.error(f"[Cache] Error checking presentation cache (non-fatal): {e}")
    return None


async def save_cached_presentation(config: PresentationConfig, spec_json: Dict[str, Any]) -> None:
    """Store generated presentation spec in deck_cache."""
    if not supabase:
        return
    cache_key = compute_presentation_hash(config)
    try:
        supabase.table("deck_cache").insert({
            "topic": f"v2_{cache_key}",
            "depth": config.depth,
            "audience": config.audience,
            "deck_json": spec_json,
        }).execute()
    except Exception as e:
        logger.warning(f"[Cache] Warning: Could not cache presentation: {e}")
